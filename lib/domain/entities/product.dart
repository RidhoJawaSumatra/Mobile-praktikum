class Product {
  final String id;
  final String name;
  final double price;
  final int quantity;
  final String imageUrl;
  final String category;
  final String description;

  Product({
    required this.id,
    required this.name,
    required this.price,
    required this.quantity,
    required this.imageUrl,
    required this.category,
    required this.description,
  });
}

